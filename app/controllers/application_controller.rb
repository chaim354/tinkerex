class ApplicationController < ActionController::Base
  # Only allow modern browsers supporting webp images, web push, badges, import maps, CSS nesting, and CSS :has.
  allow_browser versions: :modern

  # DEFAULT-DENY: the web app is session-authed (CLAUDE.md §14d), so a new subclass is private
  # from the moment it exists rather than from whenever someone remembers the line. Enforced by
  # test/architecture_invariants_test.rb, which reads the callback chain of every descendant.
  #
  # THE `unless:` IS BELT-AND-BRACES AND IS KEPT ANYWAY — read this before "simplifying" it in
  # EITHER direction, because the obvious story about it is wrong in both.
  #
  # Devise controllers DO inherit this callback: `Devise.parent_controller` defaults to
  # "ApplicationController" and `DeviseController.superclass` IS ApplicationController, so all
  # twelve Devise-lineage classes are descendants (probed). The natural conclusion — that a bare
  # `before_action :authenticate_user!` would make /users/sign_in redirect to itself — is FALSE,
  # and was checked rather than reasoned: `authenticate_user!` is generated by Devise as
  #   warden.authenticate!(opts) if !devise_controller? || opts.delete(:force)
  # (devise-5.0.4, lib/devise/controllers/helpers.rb:117-121), so it already no-ops on exactly
  # the controllers this `unless:` excludes. Dropping the condition changes NOTHING observable —
  # verified by deleting it and running the whole web suite green, auth_pages_test.rb and
  # account_enumeration_test.rb included.
  #
  # So state the consequence plainly: NO TEST IN THIS REPO CAN DISTINGUISH THE TWO SPELLINGS, and
  # none should be written to (it would assert the condition's presence, not any behaviour). What
  # the condition buys is that the app does not silently depend on an undocumented internal of a
  # generated Devise helper — if that `if !devise_controller?` ever goes away, or if
  # `authenticate_user!` is ever swapped for something of our own, the carve-out still holds and
  # the anonymous auth pages keep working. Cheap insurance against a gem-internal change no gate
  # here would catch; that is its whole value, and it is not a guard.
  #
  # Placed immediately after `allow_browser` so the chain index is unchanged from when the
  # sixteen subclasses each declared it: `require_capability!`, `require_scannable!`,
  # `set_project`, `load_addon` and `set_model` all still run AFTER auth, since a parent's
  # callbacks run before a child's.
  #
  # Does NOT reach ActiveStorage::BaseController (an ActionController::Base descendant) — the
  # direct_uploads hole in §15 is closed by the route shadow, not by this.
  before_action :authenticate_user!, unless: :devise_controller?

  # A FRESH SHARE INSTALL CONFIRMS ITS LIBRARY FOLDER BEFORE ANYTHING ELSE (K, 2026-10-20). Every
  # signed-in HTML page goes to /settings/library while Tinkerex::LibraryRoot.pending?: that page and
  # Help skip this, Devise's own pages are excluded by the condition (sign-out among them), and
  # Public:: stands on ActionController::Base and never reaches here (§14d). HTML only, so a poller
  # or a JSON door answers as itself. Off share, or once chosen, the condition is one memoised read
  # and no query. After authentication, so a signed-out visitor still meets the sign-in page first.
  before_action :require_library_folder!,
                if: -> { !devise_controller? && user_signed_in? && Tinkerex::LibraryRoot.pending? }

  # The top bar renders on every signed-in page and needs both: which upload flow this deployment
  # drives (`capabilities.port_writable?`) and which folder it uploads into.
  include LibraryCapabilities
  include FolderDestination

  # Changes to the importmap will invalidate the etag for HTML responses
  stale_when_importmap_changes

  # After a Devise sign-in (or sign-up confirmation), land on Recent — the app's front door
  # (config/routes.rb's `root to: "home#index"`). This IS Devise's own default
  # (root_path); it is stated explicitly rather than left to fall through, so a reader does not
  # have to know Devise's default to know where sign-in lands.
  def after_sign_in_path_for(_resource)
    root_path
  end

  private

  def require_library_folder!
    redirect_to settings_library_path if request.format.html?
  end
end
