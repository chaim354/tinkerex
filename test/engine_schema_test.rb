require "test_helper"

# A second, throwaway AR connection this file's strong check uses to prove the generated
# migration is actually EXECUTABLE, not merely text that looks like a subset of db/schema.rb.
# `ActiveRecord::Base#establish_connection` refuses an anonymous class ("Anonymous class is not
# allowed") because it keys the connection pool off the class's own name, so this needs to be a
# real, named class -- hence defined here rather than inline in the test.
class EngineSchemaProbe < ActiveRecord::Base
  self.abstract_class = true
end

# Guards `db/engine_schema.rb` -- the sync engine's draft consolidated migration, generated by
# `lib/engine_schema.rb` from `db/schema.rb` (CLAUDE.md §14j; the Stage 3b plan, Task 5). Same
# shape as SchemaMapTest for docs/schema-map.html: a generated file checked into a directory of
# hand-written ones goes stale silently by construction, and nothing in `bin/ci` otherwise reads
# a `db/engine_schema.rb` that no migration runner touches.
#
# THREE INDEPENDENT FAILURE MODES, kept apart on purpose:
#   * the checked-in file is behind a fresh regeneration -- someone edited db/schema.rb (i.e.
#     shipped a migration touching one of the eight tables) without re-running
#     `bin/rails engine_schema:generate`.
#   * the eight-table list itself drifted -- a ninth Sync:: model appeared, or one of the eight
#     was removed, and nobody updated the assumption this file's own header states.
#   * the generated text, though present and "current" by the first check, does not actually
#     describe a runnable, correct migration -- a text-extraction bug that happens to produce
#     well-formed-looking Ruby. Only actually RUNNING it catches this class of bug.
class EngineSchemaTest < ActiveSupport::TestCase
  test "the checked-in db/engine_schema.rb is the current schema" do
    assert EngineSchema.output_path.exist?,
           "#{EngineSchema::OUTPUT} is missing -- run `bin/rails engine_schema:generate`"
    return if EngineSchema.output_path.read == EngineSchema.render

    flunk "#{EngineSchema::OUTPUT} is stale -- run `bin/rails engine_schema:generate`"
  end

  test "the eight engine tables are exactly what app/models/sync/ declares, once each" do
    # THE GEM'S app/models/sync/, since the 2026-08-20 extraction -- the models have moved twice
    # (app/models/sync/ -> engines/tinkerex-sync/ -> their own repository) and this glob followed
    # both times. Re-derived INDEPENDENTLY from EngineSchema.tables's own glob
    # (lib/engine_schema.rb), on purpose -- the whole point of this assertion is catching the two
    # falling out of step, which a shared helper for the path would defeat. That is why the gem
    # directory is looked up again here rather than borrowed from EngineSchema.gem_root.
    gem_dir = Gem.loaded_specs.fetch("tinkerex-sync").gem_dir
    from_models = Dir.glob(File.join(gem_dir, "app/models/sync/*.rb")).map { |f|
      "Sync::#{File.basename(f, ".rb").camelize}".constantize.table_name
    }.sort

    assert_equal 8, from_models.size
    assert_equal from_models, EngineSchema.tables
    assert_equal from_models, from_models.uniq
  end

  # THE STRONG CHECK. Run the generated migration for real, against a fresh, empty database
  # carrying nothing but a stand-in `users` table (the one host dependency all eight
  # `add_foreign_key` lines name -- CLAUDE.md §14j; see lib/engine_schema.rb's header on why that
  # is Phase B's decision, not this test's), and prove the eight tables it produces have the same
  # columns, indexes and foreign keys as this app's own, already-migrated database reports for
  # the same eight tables.
  #
  # Two independently-obtained descriptions agreeing is a materially stronger proof than either
  # alone: a bug in the text extraction (a wrong block boundary, a dropped or duplicated line)
  # would make the migration fail to execute, or execute and produce a table that disagrees with
  # the live one. A bug in HOW this test reads "the live one" would not, because it goes through
  # Rails' own connection introspection (`columns`/`indexes`/`foreign_keys`) -- the identical API
  # the prefix-index guard elsewhere in this suite already trusts -- rather than a second
  # `db/schema.rb` text parse that could share a mistake with the first.
  #
  # COLUMNS ARE COMPARED AS A SET, NOT A SEQUENCE. `ActiveRecord::SchemaDumper` (and so
  # db/schema.rb, and so the migration generated from it) lists a table's columns
  # ALPHABETICALLY, which is not necessarily the PHYSICAL column order a database that
  # accumulated its schema via incremental `db:migrate` runs would report -- `versions.pinned`,
  # for instance, was added by a later migration than the rest of that table's columns. Comparing
  # an ordered array would risk failing on a difference this test has no business caring about;
  # sorting both sides removes physical order from the comparison entirely.
  test "the generated migration produces the same eight tables as the real database" do
    # `:memory:` rather than a tempfile: no path to clean up, and no window where a deferred
    # reconnect (Rails' fixture teardown probes every registered pool) could try to reopen a file
    # this test has already deleted. `pool: 1` keeps every checkout on the one connection that
    # `create_table`/the migration/`shape` all need to see the same in-memory database --
    # SQLite's `:memory:` is otherwise a fresh, empty database PER CONNECTION.
    EngineSchemaProbe.establish_connection(adapter: "sqlite3", database: ":memory:", pool: 1)
    begin
      probe = EngineSchemaProbe.connection
      probe.create_table(:users) { } # the one host table every extracted add_foreign_key names

      migration_module = Module.new
      migration_module.module_eval(EngineSchema.render, EngineSchema.output_path.to_s)
      migration = migration_module.const_get(EngineSchema::MIGRATION_CLASS).new
      migration.verbose = false # this is a correctness probe, not a real migration run -- no narration
      migration.exec_migration(probe, :up)

      real = ActiveRecord::Base.connection
      EngineSchema.tables.each do |table|
        assert_equal shape(real, table), shape(probe, table), "#{table} disagrees with the real database"
      end
    ensure
      EngineSchemaProbe.remove_connection
    end
  end

  private

  def shape(conn, table)
    {
      columns: conn.columns(table).map { |c| [ c.name, c.sql_type, c.null, c.default ] }.sort,
      indexes: conn.indexes(table).map { |i| [ i.columns, i.unique ] }.sort,
      foreign_keys: conn.foreign_keys(table).map { |fk| [ fk.from_table, fk.to_table, fk.column ] }.sort
    }
  end
  # THE FOURTH FAILURE MODE, ADDED BY THE 2026-08-20 EXTRACTION: this repo's generated
  # db/engine_schema.rb and the copy the GEM ships have drifted apart.
  #
  # Both exist, and both must. This repository still owns db/migrate/ and therefore db/schema.rb
  # (CLAUDE.md §14j -- the migrations were never rewritten for the extraction, on purpose), so the
  # generator here is still what turns THIS app's real schema into the consolidated migration. The
  # gem ships its own copy because a fresh host installing tinkerex-sync has no access to this
  # repository at all. Two checked-in descriptions of one DDL is exactly the shape CLAUDE.md warns
  # about everywhere else, and the answer is the same one used for db/engine_schema.rb itself: not
  # "have only one", but "make the second one unable to drift quietly".
  #
  # WHAT THIS TURNS RED, AND WHAT TO DO ABOUT IT: a migration lands here touching one of the eight
  # tables, `bin/rails engine_schema:generate` updates db/engine_schema.rb, the first test above
  # goes green again -- and this one fails, because the gem is still shipping the old DDL. The fix
  # is a commit in chaim354/tinkerex-sync updating its db/engine_schema.rb, then
  # `bundle update tinkerex-sync` here. That cross-repo obligation is real work, and a schema
  # change is precisely when it must be impossible to forget.
  test "the gem ships the same engine schema this repo generates" do
    gem_copy = Pathname.new(Gem.loaded_specs.fetch("tinkerex-sync").gem_dir).join("db/engine_schema.rb")

    assert gem_copy.exist?,
           "the tinkerex-sync gem ships no db/engine_schema.rb -- a fresh host has no way to " \
           "create the eight engine tables. Expected it at #{gem_copy}."

    assert_equal EngineSchema.render, gem_copy.read,
                 "the tinkerex-sync gem's db/engine_schema.rb no longer matches what this repo " \
                 "generates from db/schema.rb. Update it in chaim354/tinkerex-sync and " \
                 "`bundle update tinkerex-sync` here -- see this test's own comment."
  end
end
